export class PoolSim extends FakeSim {
  override device(udid: string): Promise<DeviceInfo | undefined> {
    if (!this.devices.has(udid)) this.addDevice(udid, 'Shutdown', 'agentlane-pool');
    return super.device(udid);
  }
}

export const ANDROID_TOOLCHAIN = 'jdk openjdk version "17.0.20"; gradle generated by the build; sdk platforms/android-36 2';

export const toolchain = (java = true, android = ANDROID_TOOLCHAIN): Toolchain => ({
  xcodeVersion: () => Promise.resolve('Xcode 26.6 Build version 17F42'),
  androidToolchain: () => Promise.resolve(android),
  localeCharmap: () => Promise.resolve('UTF-8'),
  findJava17: () => Promise.resolve(java ? { home: '/jdk17', version: '17.0.20' } : null),
});

export function alive(pid: number): boolean {
  const stat = spawnSync('ps', ['-o', 'stat=', '-p', String(pid)], { encoding: 'utf8' }).stdout.trim();
  return stat !== '' && !stat.startsWith('Z');
}

export async function until(check: () => boolean, ms = 5000): Promise<void> {
  const end = Date.now() + ms;
  while (!check()) {
    if (Date.now() > end) throw new Error('timed out waiting');
    await new Promise(resolve => setTimeout(resolve, 50));
  }
}

export function sleeper(): ChildProcess {
  return spawn(process.execPath, ['-e', 'setTimeout(() => {}, 60000)'], { stdio: 'ignore' });
}

export function listener(port: number): Promise<ChildProcess> {
  const child = spawn(
    process.execPath,
    ['-e', `require('net').createServer().listen(${String(port)}, '127.0.0.1', () => console.log('up'))`],
    {
      stdio: ['ignore', 'pipe', 'ignore'],
    },
  );
  return new Promise(resolve => {
    child.stdout.once('data', () => {
      resolve(child);
    });
  });
}

export interface World {
  root: string;
  project: string;
  state: string;
  sim: PoolSim;
  emulators: Map<string, FakeAdb>;
  sdk: string;
  lines: string[];
  deps: (over?: Partial<EnvDeps> & { owner?: number }) => EnvDeps;
  write: (config: unknown) => void;
  read: (file: string) => string;
  processes: () => { service: string; pid: number; start: string; cwd: string | null }[];
  driverStarts: { lane: string; stateDir: string; afterLaunch: boolean }[];
  browser: FakeBrowser;
}

export function world(t: TestContext): World {
  const root = fs.realpathSync(tempDir('up'));
  const state = path.join(root, 'state');
  fs.mkdirSync(state, { recursive: true });
  fs.writeFileSync(
    path.join(state, 'config.json'),
    JSON.stringify({
      ports: { metro: [METRO, METRO + 3], api: [API, API + 3], web: [WEB, WEB + 3], browser: [BROWSER, BROWSER + 9] },
    }),
  );
  const project = path.join(root, 'repo');
  fs.mkdirSync(project);
  assert.equal(spawnSync('git', ['init', '-q', project]).status, 0);
  fs.writeFileSync(path.join(project, '.gitignore'), 'build/\nnode_modules/\n*.log\n*.env\n');
  fs.writeFileSync(path.join(project, 'app.json'), '{"name":"fake"}\n');
  fs.writeFileSync(path.join(project, 'metro.mjs'), METRO_SERVER);
  fs.writeFileSync(path.join(project, 'server.mjs'), API_SERVER);
  const write = (config: unknown) => {
    fs.writeFileSync(path.join(project, 'agentlane.json'), JSON.stringify(config, null, 2));
  };
  write(CONFIG);
  const sim = new PoolSim();
  const devices = new FakeDevices(path.join(root, 'devices'));
  const avds = new FakeDevices(path.join(root, 'avds'), 'android');
  const emulators = new Map<string, FakeAdb>();
  const adb = (serial: string): FakeAdb => {
    const known = emulators.get(serial) ?? new FakeAdb(serial);
    emulators.set(serial, known);
    return known;
  };
  const sdk = path.join(root, 'sdk');
  for (const tool of ['platform-tools/adb', 'emulator/emulator']) {
    fs.mkdirSync(path.dirname(path.join(sdk, tool)), { recursive: true });
    fs.writeFileSync(path.join(sdk, tool), '#!/bin/sh\nexit 1\n', { mode: 0o755 });
  }
  const lines: string[] = [];
  const driverStarts: World['driverStarts'] = [];
  const browser = new FakeBrowser(root);
  const env = {
    PATH: process.env.PATH,
    HOME: process.env.HOME,
    AGENTLANE_STATE_DIR: state,
    ANDROID_HOME: sdk,
    CLAUDE_CONFIG_DIR: path.join(root, 'claude-config'),
    XDG_STATE_HOME: path.join(root, 'xdg-state'),
  };
  const processes = () =>
    readRegistryStatus({ dir: state, processes: systemProcesses, devices: { ios: devices, android: avds } }).lanes.flatMap(
      c => c.processes,
    );
  t.after(() => {
    for (const p of processes()) realServiceSystem.signalGroup(p.pid, 'SIGKILL');
    browser.removeSocketDirs();
    fs.rmSync(root, { recursive: true, force: true });
  });
  return {
    root,
    project,
    state,
    sim,
    emulators,
    sdk,
    lines,
    write,
    processes,
    driverStarts,
    browser,
    read: file => fs.readFileSync(path.join(project, file), 'utf8'),
    deps: (over = {}) => ({
      env: { ...env, AGENTLANE_OWNER_PID: String(over.owner ?? process.pid) },
      cwd: project,
      log: line => lines.push(line),
      processes: systemProcesses,
      ports: tcpProbe,
      devices: { ios: devices, android: avds },
      sim,
      adb,
      system: realServiceSystem,
      toolchain: toolchain(),
      startDriver: (lane, stateDir) => {
        driverStarts.push({ lane: lane.id, stateDir, afterLaunch: sim.calls.some(c => c.startsWith('launch')) });
        return Promise.resolve();
      },
      clock: systemClock,
      browser,
      ...over,
    }),
  };
}

